/** Closed vocabulary only. Never pass request data or raw exceptions to a sink. */
export const IMAGE_DIAGNOSTIC_CODES = [
  'AUTH_STARTED', 'AUTH_OK', 'AUTH_FAILED',
  'DETACH_STARTED', 'DETACH_OK', 'DETACH_FAILED',
  'CLAIM_STARTED', 'CLAIM_OK', 'CLAIM_FAILED',
  'INITIAL_REVALIDATION_STARTED', 'INITIAL_REVALIDATION_OK', 'INITIAL_REVALIDATION_FAILED',
  'INITIAL_GET_STARTED', 'INITIAL_GET_ABSENT', 'INITIAL_GET_PRESENT', 'INITIAL_GET_AMBIGUOUS',
  'INITIAL_STORAGE_MISMATCH',
  'PRE_DELETE_REVALIDATION_STARTED', 'PRE_DELETE_REVALIDATION_OK', 'PRE_DELETE_REVALIDATION_FAILED',
  'STORAGE_DELETE_STARTED', 'STORAGE_DELETE_ACCEPTED', 'STORAGE_DELETE_ABSENT',
  'STORAGE_DELETE_REJECTED', 'STORAGE_DELETE_AMBIGUOUS', 'STORAGE_DELETE_SKIPPED',
  'POST_DELETE_GET_STARTED', 'POST_DELETE_GET_ABSENT', 'POST_DELETE_GET_PRESENT', 'POST_DELETE_GET_AMBIGUOUS',
  'FINAL_REVALIDATION_STARTED', 'FINAL_REVALIDATION_OK', 'FINAL_REVALIDATION_FAILED', 'FINAL_REVALIDATION_STORAGE_PRESENT',
  'COMPLETE_STARTED', 'COMPLETE_OK', 'COMPLETE_FAILED', 'COMPLETE_HTTP_FAILED', 'COMPLETE_TRANSPORT_FAILED', 'COMPLETE_BODY_INVALID',
  'TARGETED_DELETION_DELETED', 'TARGETED_DELETION_RETAINED', 'TARGETED_DELETION_ALREADY_COMPLETED_UNVERIFIED',
  'TARGETED_DELETION_UNAUTHENTICATED', 'TARGETED_DELETION_INVALID_INPUT', 'TARGETED_DELETION_CONFIGURATION_ERROR',
  'TARGETED_DELETION_FORBIDDEN', 'TARGETED_DELETION_CONFLICT', 'TARGETED_DELETION_RECOVERY_REQUIRED',
  'ROUTE_RECOVERY_REQUIRED',
  'PENDING_RESTORED', 'API_DELETED_CONFIRMED', 'API_RETAINED', 'API_RECOVERY_REQUIRED', 'API_RESPONSE_AMBIGUOUS',
  'IMAGE_SYNC_STARTED', 'IMAGE_SYNC_OK', 'IMAGE_SYNC_FAILED', 'IMAGE_STILL_ASSOCIATED',
  'PENDING_STORAGE_FAILED', 'EDITOR_UNLOCKED',
] as const;
export type ImageDiagnosticCode = typeof IMAGE_DIAGNOSTIC_CODES[number];
export type ImageDiagnostic = (code: ImageDiagnosticCode, httpStatus?: number) => void;
const allowed = new Set<string>(IMAGE_DIAGNOSTIC_CODES);
export function createImageDiagnostic(enabled: boolean, sink: (...args: (string | number)[]) => void): ImageDiagnostic {
  return (code, status) => {
    if (!enabled || !allowed.has(code)) return;
    try {
      if (typeof status === 'number' && Number.isInteger(status) && status >= 100 && status <= 599) sink(code, status);
      else sink(code);
    } catch { /* Observability must never change operation outcomes. */ }
  };
}
